package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/manojrevenkar12-web/query-plan-insights/internal/eval"
)

// Results is reports/results.json: what the README, RESULTS.md and the web app's evaluation page show.
type Results struct {
	GeneratedAt time.Time      `json:"generatedAt"`
	HeldoutPin  string         `json:"heldoutPin"`
	HeldoutRuns int            `json:"heldoutRuns"`
	Dev         *SetReport     `json:"dev,omitempty"`
	Heldout     *SetReport     `json:"heldout,omitempty"`
	Overhead    *eval.Overhead `json:"overhead,omitempty"`
}

func readJSON(path string, v any) bool {
	b, err := os.ReadFile(path)
	if err != nil {
		return false
	}
	return json.Unmarshal(b, v) == nil
}

func writeReport(root string) error {
	reports := filepath.Join(root, "reports")
	spec, err := eval.LoadSpec(root)
	if err != nil {
		return err
	}
	r := Results{GeneratedAt: time.Now().UTC(), HeldoutPin: spec.Pin()}
	var dev, held SetReport
	var over eval.Overhead
	if readJSON(filepath.Join(reports, "eval-dev.json"), &dev) {
		r.Dev = &dev
	}
	if readJSON(filepath.Join(reports, "eval-heldout.json"), &held) {
		r.Heldout = &held
	}
	if readJSON(filepath.Join(reports, "overhead.json"), &over) {
		r.Overhead = &over
	}
	if b, err := os.ReadFile(filepath.Join(reports, "heldout-runs.log")); err == nil {
		for _, line := range strings.Split(string(b), "\n") {
			if strings.TrimSpace(line) != "" {
				r.HeldoutRuns++
			}
		}
	}
	if err := writeJSON(filepath.Join(reports, "results.json"), r); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(reports, "RESULTS.md"), []byte(resultsMarkdown(r)), 0o644); err != nil {
		return err
	}
	return updateREADME(filepath.Join(root, "README.md"), block(r))
}

func pct(n, d int) string {
	if d == 0 {
		return "–"
	}
	return fmt.Sprintf("%d/%d", n, d)
}

func summaryRow(name string, s *SetReport) string {
	if s == nil {
		return fmt.Sprintf("| %s | not run | | | | | | |\n", name)
	}
	m := s.Summary
	return fmt.Sprintf("| %s | %s | %s | %s | %s | %d | %.0f s | %.0f s |\n", name, pct(m.Detected, m.Faults),
		pct(m.CauseCorrect, m.Faults), pct(m.SuggestionCorrect, m.Faults), pct(m.Resolved, m.Faults), m.FalseAlarms,
		m.MedianDetectS, m.MedianResolveS)
}

// block is the numbers dashboard at the top of the README.
func block(r Results) string {
	var b strings.Builder
	b.WriteString("Faults injected into a real PostgreSQL 16 under a running workload; generated by `make eval report`.\n\n")
	b.WriteString("| Set | Detected | Cause right at open | Fix suggested | Fix confirmed | False alarms | Median time to detect | Median time to confirm fix |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|\n")
	b.WriteString(summaryRow("Development (shop app, tuned on)", r.Dev))
	b.WriteString(summaryRow("Held-out (billing app, run once)", r.Heldout))
	if o := r.Overhead; o != nil {
		fmt.Fprintf(&b, "\nCollector overhead: %.1f%% of closed-loop point-lookup throughput (%.0f vs %.0f queries/s, %d rounds), "+
			"%.1f ms per one-second collection.\n", o.OverheadPct, o.OnMean, o.OffMean, o.Rounds, o.TickMeanMs)
	}
	fmt.Fprintf(&b, "\nHeld-out set pinned at `%s`, run %d time(s). Per-scenario detail: [reports/RESULTS.md](reports/RESULTS.md).\n",
		short(r.HeldoutPin), r.HeldoutRuns)
	return b.String()
}

func short(s string) string {
	if len(s) > 12 {
		return s[:12]
	}
	return s
}

func resultsMarkdown(r Results) string {
	var b strings.Builder
	b.WriteString("# Evaluation results\n\nGenerated by `qpi-eval -report` from the files in this directory. Do not edit.\n\n")
	b.WriteString(block(r))
	for _, s := range []*SetReport{r.Dev, r.Heldout} {
		if s == nil {
			continue
		}
		title := map[string]string{"dev": "Development set", "heldout": "Held-out set"}[s.Set]
		fmt.Fprintf(&b, "\n## %s\n\nRun %s.\n\n", title, s.GeneratedAt.Format(time.RFC3339))
		b.WriteString("| Scenario | Target query | Detected after | Cause at open (expected) | Fix suggested | Fix confirmed after | Also flagged (expected) | False alarms |\n")
		b.WriteString("|---|---|---|---|---|---|---|---|\n")
		for _, o := range s.Outcomes {
			if o.Control {
				fmt.Fprintf(&b, "| %s | none (control) | | | | | | %s |\n", o.Scenario, list(o.FalseAlarms))
				continue
			}
			det, fix := "missed", "no"
			if o.Detected {
				det = fmt.Sprintf("%.0f s", o.DetectSeconds)
			}
			if o.Resolved {
				fix = fmt.Sprintf("%.0f s", o.ResolveSeconds)
			}
			cause := fmt.Sprintf("%s (%s)", orDash(o.CauseAtOpen), o.WantCause)
			fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s | %s | %s | %s |\n", o.Scenario, o.Target, det, cause,
				yes(o.SuggestionCorrect), fix, list(o.CollateralFound), list(o.FalseAlarms))
		}
		b.WriteString("\nWhat each scenario does, and the verification text the collector wrote when the fix landed:\n\n")
		for _, o := range s.Outcomes {
			fmt.Fprintf(&b, "- **%s**: %s", o.Scenario, o.About)
			if o.Verification != "" {
				fmt.Fprintf(&b, " Verified: _%s_.", o.Verification)
			}
			if o.Error != "" {
				fmt.Fprintf(&b, " Error: %s.", o.Error)
			}
			b.WriteString("\n")
		}
	}
	return b.String()
}

func list(xs []string) string {
	if len(xs) == 0 {
		return "none"
	}
	return strings.Join(xs, ", ")
}

func orDash(s string) string {
	if s == "" {
		return "–"
	}
	return s
}

func yes(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}

const startMark, endMark = "<!-- results:start -->", "<!-- results:end -->"

func updateREADME(path, content string) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil // no README yet
	}
	s := string(b)
	i, j := strings.Index(s, startMark), strings.Index(s, endMark)
	if i < 0 || j < i {
		return fmt.Errorf("README.md lacks the %s ... %s markers", startMark, endMark)
	}
	s = s[:i+len(startMark)] + "\n" + content + s[j:]
	return os.WriteFile(path, []byte(s), 0o644)
}
